"""PDF validation: what is accepted, and a corpus of files that must not be.
No database; every PDF is generated by `tests.pdf_files`."""

import io

import pytest

from app.assets.document import MAX_PAGES, inspect_pdf
from app.exceptions import DocumentInvalidError
from tests.images import png
from tests.pdf_files import (
    build_pdf,
    build_pdf_with_object_stream,
    encrypted,
    first_extra,
)

EXTRA = first_extra()  # the number of the first extra object of a 1-page file


def reason_of(data: bytes) -> str:
    with pytest.raises(DocumentInvalidError) as caught:
        inspect_pdf(io.BytesIO(data))
    return caught.value.reason


def pages_of(data: bytes) -> int:
    return inspect_pdf(io.BytesIO(data)).page_count


# --- accepted --------------------------------------------------------------------------


@pytest.mark.parametrize("pages", [1, 3, MAX_PAGES])
def test_a_plain_pdf_is_accepted_and_its_pages_counted(pages: int) -> None:
    assert pages_of(build_pdf(pages=pages)) == pages


def test_the_file_is_read_not_changed() -> None:
    data = build_pdf(pages=2)
    stream = io.BytesIO(data)

    inspect_pdf(stream)

    assert stream.getvalue() == data and stream.tell() == 0


def test_a_nested_page_tree_is_counted() -> None:
    nested = build_pdf(
        pages=2,
        pages_dict="",
        extra=(
            f"<< /Type /Pages /Parent 2 0 R /Kids [{first_extra(2) + 1} 0 R] /Count 1 >>",
            "<< /Type /Page /Parent 7 0 R /MediaBox [0 0 10 10] >>",
        ),
    )
    # Page 3 and 5 stay as they were; the nested node is not wired in: 2 pages.
    assert pages_of(nested) == 2


def test_a_pdf_with_object_streams_is_accepted() -> None:
    data = build_pdf_with_object_stream("<< /Type /Metadata /Note (hola) >>")

    assert pages_of(data) == 1


def test_plain_uri_links_are_allowed() -> None:
    link = (
        "<< /Type /Annot /Subtype /Link /Rect [0 0 50 20] "
        "/A << /S /URI /URI (https://example.org/a) >> >>"
    )
    data = build_pdf(page=f"/Annots [{EXTRA} 0 R]", extra=(link,))

    assert pages_of(data) == 1


def test_internal_destinations_and_open_actions_that_only_navigate_are_allowed() -> (
    None
):
    data = build_pdf(catalog="/OpenAction [3 0 R /Fit]")

    assert pages_of(data) == 1


def test_metadata_is_not_a_reason_to_refuse() -> None:
    info = "<< /Author (Ana) /Title (Guía) /Producer (Writer) >>"
    data = build_pdf(extra=(info,), trailer=f"/Info {EXTRA} 0 R")

    assert pages_of(data) == 1


# --- not a PDF -------------------------------------------------------------------------


@pytest.mark.parametrize(
    "data",
    [
        b"",
        b"hello",
        png(),
        b"<html><script>alert(1)</script></html>",
        b"junk before the magic\n" + build_pdf(),
        b" %PDF-1.7\n" + build_pdf()[9:],
        b"%PDF",
        b"PK\x03\x04" + b"\x00" * 100,
    ],
)
def test_anything_without_the_magic_at_the_start_is_not_a_pdf(data: bytes) -> None:
    assert reason_of(data) == "not_pdf"


# --- corrupt ---------------------------------------------------------------------------

GOOD = build_pdf(pages=2)


@pytest.mark.parametrize(
    "data",
    [
        b"%PDF-1.7\n",
        b"%PDF-1.7\n" + b"\x00" * 200,
        b"%PDF-1.7\nthis is not a pdf at all\n%%EOF\n",
        GOOD[: len(GOOD) // 2],
        GOOD[:-40],
        GOOD[: GOOD.index(b"xref")],
        GOOD.replace(b"startxref\n", b"startxref\n9"),
        GOOD.replace(b"/Root 1 0 R", b"/Root 99 0 R"),
        GOOD.replace(b"/Type /Catalog", b"/Type /Nothing /X"),
        build_pdf(pages=1, pages_dict="/Kids [2 0 R]"),
        build_pdf(pages=0),
        build_pdf(extra=("<< /Type /Pages /Kids [ 2 0 R ] >>",), count=1).replace(
            b"/Kids [3 0 R]", b"/Kids [2 0 R]"
        ),
    ],
    ids=[
        "header only",
        "header and zeros",
        "header and text",
        "cut in half",
        "cut before the end",
        "cut before the xref",
        "bad startxref",
        "missing root",
        "no catalog type",
        "page tree that lists itself",
        "no pages",
        "page tree loop",
    ],
)
def test_broken_files_are_corrupt(data: bytes) -> None:
    assert reason_of(data) == "corrupt"


# --- encrypted -------------------------------------------------------------------------


def test_an_encrypted_pdf_is_refused() -> None:
    assert reason_of(encrypted(build_pdf())) == "encrypted"


# --- too many pages ---------------------------------------------------------------------


def test_one_page_over_the_limit_is_refused() -> None:
    assert reason_of(build_pdf(pages=MAX_PAGES + 1)) == "too_many_pages"


def test_a_page_count_that_lies_is_refused_either_way() -> None:
    # Declares a huge book but lists a single page.
    assert reason_of(build_pdf(pages=1, count=100_000)) == "too_many_pages"
    # Declares one page but lists far more.
    assert reason_of(build_pdf(pages=MAX_PAGES + 50, count=1)) == "too_many_pages"


def test_a_huge_declared_count_is_refused_without_walking_the_tree() -> None:
    assert reason_of(build_pdf(pages=1, count=10**12)) == "too_many_pages"


