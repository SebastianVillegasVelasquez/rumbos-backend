@pytest.mark.parametrize("data", ACTIVE.values(), ids=list(ACTIVE))
def test_active_content_is_refused(data: bytes) -> None:
    assert reason_of(data) == "active_content"


def test_active_content_in_a_broken_file_is_still_reported_as_such() -> None:
    data = build_pdf(catalog="/OpenAction << /S /JavaScript /JS (x) >>")

    assert reason_of(data[: len(data) // 2]) == "active_content"


def test_a_name_that_merely_starts_like_a_forbidden_one_is_fine() -> None:
    data = build_pdf(catalog="/Lang (es) /Note << /JSON (x) /JavaScripture (y) >>")

    assert pages_of(data) == 1


def test_text_that_mentions_javascript_is_not_active_content() -> None:
    info = "<< /Subject (A guide to /JavaScript and /Launch actions) >>"
    data = build_pdf(extra=(info,), trailer=f"/Info {EXTRA} 0 R")

    assert pages_of(data) == 1
